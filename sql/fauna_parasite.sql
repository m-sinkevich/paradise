### Как обезвредить
1. **Наденьте перчатки.** Любые плотные. Голыми руками не трогать: слизь на брюшке жжёт кожу.
2. **Не давить и не бить.** Раздавленный клещ брызжет кислотной кровью и выпускает облако спор.
3. **Не дёргать.** Крючья и зубы останутся в коже или ткани, рана воспалится.
4. **Подсуньте под клеща плоский предмет**: пластинку, карточку, нож плашмя.
5. **Поверните на четверть оборота против часовой стрелки.** Крючья выходят сами, клещ отваливается на пластину.
