### Как живёт
- Ночью снаружи сидит во мху и на скалах, ждёт тёплое тело. В модуль попадает **на одежде, скафандрах, ящиках с грузом и образцах**.
- Находит жертву по теплу и дыханию: бирюзовые точки на спине — тепловые органы.
- Кусает присоской с кольцом зубов. Слюна обезболивает, поэтому человек укуса не чувствует 10–20 минут.
- Напившись крови, ищет тёплое укрытие (за приборами, под койками, в одежде) и **откладывает 30–50 яиц**. Через несколько часов модуль заражён.

### Почему нельзя давить
- Внутри — **кислотная гемолимфа**: при раздавливании брызжет, обжигает кожу и глаза.
- Светящиеся точки — мешочки со **спорами**. При ударе или раздавливании лопаются, споры попадают в лёгкие и раны.
- Крючья на ногах загнуты по спирали **против часовой стрелки**. Если дёргать, они рвут ткань и обламываются в коже. Если повернуть на четверть оборота против часовой, они выходят чисто. На этом и держится способ снятия.

### Что делать с пойманными
- В закрытом контейнере клещ живёт около суток. **Соль или спирт** в контейнере убивают его за минуты, споры не выходят.
- Огонь не годится: панцирь лопается, споры разлетаются.
- Пустые панцири и яйца — ценный материал: из слюны можно получить **обезболивающее**, а светящиеся мешочки реагируют на тепло (самодельный датчик тепла).

