*Местное название — «саван». Класс опасности: I. Главная причина запрета выходить ночью без скафандра.*

### Почему ночью опасно
Ночница **не нападает**. Опасен **газ**, который она выделяет. При каждом взмахе крыльев из желёз на брюшке выходит облако без цвета и почти без запаха (слабый сладкий привкус), смешанное с пыльцой крыльев. В газе — **нейротоксин**. Одна особь отравляет воздух вокруг себя на сотни метров, стая — всю округу до рассвета. Днём токсин разлагается на свету, поэтому днём можно ходить без защиты.

**Действие на человека:** головокружение → видения и «шёпот» → потеря ориентации, тянет идти на свет → провалы в памяти, потеря сознания. **Без скафандра или фильтрующей маски ночью не выходить.**

### Почему их не перебить
- **Живучие.** Пули и осколки проходят через мягкое тело, раны затягиваются за минуты. Огонь отпугивает, но не убивает.
- **Плодовитые.** Самка откладывает сотни яиц в трещины скал. Стая восстанавливается за несколько ночей.

Обычным оружием проблему не решить. Нужно оружие, которое ночницы **разнесут сами**.

### Решение: вирусные снаряды из огнеплодника
Слабое место ночниц — **нервные узлы под пушком**, в сочленениях крыльев и на брюшке. Липкие плоды огнеплодника («кровавая ягода», П-02) **прилипают** именно туда. Если заселить плоды вирусом, они доставят заразу прямо в нервную систему.

**1. Сбор плодов**
- Собрать **плоды огнеплодника** — нужно не меньше **6 на каждую ночницу**, лучше с запасом.
- Только в плотных перчатках и закрытой одежде: нити ядовиты (см. медкарту Б-02).
- Плоды нести в закрытом контейнере, чтобы нити не прилипли к сборщику.

**2. Заселение вируса** (выполняет ксенобиолог в лаборатории модуля)
1. Нужен **образец ночницы**: пыльца с крыльев, обрывок крыла или кусочек пушка. Вирус выращивается против конкретного вида.
2. Растереть образец с соком светомоха (П-04): мох подавляет чужие бактерии и оставляет нужный штамм.
3. Выдерживать смесь в тепле и темноте **15 минут** (игровое время) — вирус размножается.
4. Каждый плод огнеплодника наколоть иглой и ввести каплю культуры в железы-ямки.
5. Заражённые плоды темнеют до бордового и **гаснут** — свечение пропадает. Плод готов. Работает до рассвета: потом вирус в плоде погибает.

**3. Применение**
- Метать плоды в ночницу с близкого расстояния, в крылья у тела и в брюшко.
- Плоды прилипают к сочленениям и пушку. Каждый плод — новая доза вируса.
- Когда на одной ночнице окажется **6 и больше плодов**, количество становится критическим: нервная система отказывает, ночница падает и **погибает** в течение нескольких минут.
- Работать **только в скафандрах**: охота идёт ночью, в облаке газа.

**4. Цепная реакция**
Погибшая ночница выделяет запах-зов. Сородичи **обязательно** слетаются к телу, касаются его и заражаются. Заражённые разносят вирус по стае и по местам кладки. За **одну-две ночи** гибнет вся колония, яйца не развиваются.

**5. Результат**
Нет ночниц — нет газа. Воздух очищается к следующей ночи. **Можно ходить без скафандров.**

> *Игровое правило для мастера:* ночница погибает, когда на неё попало 6 и больше заражённых плодов. После первой гибели к телу прилетают остальные — мастер объявляет вымирание колонии к следующему циклу, газ исчезает.$q$;
